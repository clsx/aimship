import fs from 'node:fs/promises';
import { reviewStatus } from './approvals.mjs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { atomicWrite, exists, hash, json, readJSON, noSymlinks } from './io.mjs';
import { resolveRef } from './documents.mjs';

const paths = dir => ({ view: path.join(dir,'status.md'), meta: path.join(dir,'.aimship/view.json') });
export async function viewStatus(directory, state) {
  if (state.schemaVersion !== 2) return { status:'legacy', recovery:'Explicitly migrate this delivery before generating its view.' };
  const p=paths(directory);
  try {
    if (!await exists(p.view)) return { status:'missing', recovery:'Run render at the current revision.' };
    await noSymlinks(p.view); await noSymlinks(p.meta);
    if (!await exists(p.meta)) return { status:'modified', recovery:'No trusted generation digest; preserve edits with render --preserve-edits.' };
    const meta=await readJSON(p.meta), raw=await fs.readFile(p.view,'utf8');
    if (hash(raw)!==meta.hash) return { status:'modified', recovery:'Inspect the edits, then render --preserve-edits.' };
    const current=meta.deliveryId===state.deliveryId && meta.revision===state.revision;
    return { status:current?'current':'stale', revision:meta.revision, recovery:current?null:'Run render; do not replay the saved business update.' };
  } catch(error) { return {status:'error',reason:error.code ?? error.message,recovery:'Inspect view/metadata paths; preserve untrusted content before render.'}; }
}
const cell = x => String(x ?? 'not recorded').replaceAll('|','\\|').replaceAll('\n',' ');
const link = ref => `[${ref.replaceAll('[','\\[').replaceAll(']','\\]')}](${ref.replaceAll(' ','%20').replaceAll('(','%28').replaceAll(')','%29')})`;
async function available(directory,state,ref) {
  if (/^https?:\/\//.test(ref)) return true;
  const p=resolveRef(directory,state,ref); return p && await exists(p);
}
export async function renderText(directory,state) {
  const artifactLink=ref=> {
    if (!ref.startsWith('repo:')) return link(ref);
    const target=resolveRef(directory,state,ref);
    const fragment=ref.includes('#')?'#'+ref.split('#')[1]:'';
    return target ? `[${cell(ref)}](${encodeURI(target).replaceAll('(','%28').replaceAll(')','%29')}${fragment})` : cell(ref);
  };
  const lines=['# Delivery status','','Generated by Aimship. Edit formal documents and structured state, not this page.','', '## Goal and basis','', cell(state.goal.summary), '',`Endpoint: ${cell(state.goal.endpoint)}`,''];
  if (await available(directory,state,state.goalRef)) lines.push(artifactLink(state.goalRef),'');
  lines.push('## Associated engineering objects','','| ID | Actual checkout/worktree | Role |','| --- | --- | --- |');
  for (const r of state.repositories) lines.push(`| ${cell(r.id)} | ${cell(r.path)} | ${cell(r.role)} |`);
  if (!state.repositories.length) lines.push('| — | No repository registered | — |');
  lines.push('','## Stage progress','','| Run / scope | Stage | Progress | Result | Applicability |','| --- | --- | --- | --- | --- |');
  for (const r of state.stageRuns) lines.push(`| ${cell(r.id)} / ${cell(r.scope)} | ${r.stage} | ${r.progress} | ${cell(r.result)} | ${cell(r.applicability)} |`);
  lines.push('','## Current work, blockers and next action','',`Current: ${cell(state.currentRun)}`, '',`Next: ${cell(state.next.action)}`);
  for (const r of state.stageRuns.filter(r=>r.progress==='blocked')) lines.push(`- Blocked: ${cell(r.id)} — ${cell(r.scope)}`);
  for (const c of state.openChanges.filter(c=>c.status==='open')) lines.push(`- Open change/question: ${link(c.ref)}`);
  if (state.checkpoint) lines.push('',`Unfinished facts: ${cell(state.checkpoint.summary)}`);
  const review = await reviewStatus(directory,state);
  lines.push('', '## Document review', '', `Review protocol: ${review.compatibility}`, `Next stage: ${cell(review.nextStage)}`, '', '| Document | Version | Review status | Approval record |', '| --- | --- | --- | --- |');
  for (const d of review.documents) lines.push(`| ${artifactLink(d.path)} | ${cell(d.version)} | ${d.status} | ${cell(d.approval)} |`);
  for (const p of review.pending) lines.push(`- Awaiting review: ${artifactLink(p.document)} (${cell(p.run)}; ${p.status})`);
  lines.push('', 'Approval records bind content and user decision evidence; the tool does not authenticate the user.', '');
  lines.push('','## Artifacts and plan','');
  const refs=new Set([...(state.documents??[]).map(d=>d.path),...state.stageRuns.flatMap(r=>[...r.outputRefs,r.resultRef].filter(Boolean)),...(state.next.inputRefs??[])]);
  for (const ref of refs) if (await available(directory,state,ref)) lines.push(`- ${artifactLink(ref)}`);
  lines.push('','## Independent outcomes and generation','',`Goal: ${state.outcome.goal}`,`Acceptance: ${state.outcome.acceptance}`,`Merge: ${state.outcome.mergeRef?link(state.outcome.mergeRef):'not recorded'}`,`Deployment: ${state.outcome.deploymentRef?link(state.outcome.deploymentRef):'not recorded'}`,'',`Delivery: ${state.deliveryId}`,`State revision: ${state.revision}`,`Rules: ${state.rulesVersion}`,`State saved: ${state.updatedAt}`,'','Matching revisions do not establish document semantics or authorization.','');
  return lines.join('\n');
}
export async function generateView(directory,state,preserveEdits=false) {
  const p=paths(directory); const diagnostic=await viewStatus(directory,state);
  let preservedPath;
  try {
    if (['modified','error'].includes(diagnostic.status) && await exists(p.view)) {
      if (!preserveEdits) return {...diagnostic,status:'protected'};
      await noSymlinks(p.view);
      preservedPath=path.join(directory,'.aimship',`status-edits-${randomUUID()}.md`);
      await atomicWrite(preservedPath,await fs.readFile(p.view));
    }
    const text=await renderText(directory,state);
    await atomicWrite(p.view,text);
    await atomicWrite(p.meta,json({deliveryId:state.deliveryId,revision:state.revision,hash:hash(text)}));
    return {status:'current',revision:state.revision,...(preservedPath?{preservedPath}:{})};
  } catch(error) {return {status:'error',reason:error.code??error.message,...(preservedPath?{preservedPath}:{}),recovery:'State was saved. Repair the view paths, then render at the returned revision; do not replay update.'};}
}
export async function savedResult(directory,state) {
  return {...state,writeResult:{stateSaved:true,revision:state.revision,view:await generateView(directory,state)}};
}
